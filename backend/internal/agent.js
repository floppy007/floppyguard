/**
 * Validate that a URL is safe to write into config.env via sed and to use as a
 * shell-interpolated curl target on the agent. Rejects anything that isn't a
 * plain http(s) URL — same threat model as getInstallScript's URL guard.
 *
 * @param {string|null|undefined} url
 * @returns {string|null}  the URL if valid, otherwise null
 */
/**
 * The public/fallback hub URL: sanitizeHubUrl plus https only. Agents use it when
 * the tunnel path is down, i.e. across the internet — a plain-http fallback would
 * carry the bearer token and the root-applied WireGuard config in cleartext.
 *
 * @param {string} url
 * @returns {string|null}
 */
function sanitizeFallbackHubUrl(url) {
	const clean = sanitizeHubUrl(url);
	return clean && /^https:\/\//i.test(clean) ? clean : null;
}

function sanitizeHubUrl(url) {
	if (!url || typeof url !== "string") return null;
	const trimmed = url.trim().replace(/\/+$/, "");
	if (!trimmed) return null;
	try {
		const parsed = new URL(trimmed);
		if (!["http:", "https:"].includes(parsed.protocol)) return null;
	} catch {
		return null;
	}
	// config.env writes use sed with `|` delimiter and bash double quotes; curl
	// interpolates the value unquoted-safe. Reject shell/sed metacharacters.
	if (/[$`\\;|&(){}<>!#"'\s]/.test(trimmed)) return null;
	return trimmed;
}

// `mode` and `wg_interface` are interpolated into the same root-sourced
// config.env heredoc (AGENT_MODE="..." / WG_INTERFACE="...") in
// getInstallScript — the JS template substitutes the value BEFORE the
// single-quoted heredoc is written, so a quote+newline closes the assignment
// and injects arbitrary lines.
// wg_interface additionally flows into `wg-quick up "$iface"` and the path
// /etc/wireguard/$iface.conf on the agent. Whitelist both before storage.
const VALID_AGENT_MODES = ["native"];
// config_text is hub-generated (agent upload → normalizeAgentConfig, then
// syncAgentConfigs) and the agent applies its PostUp/PreUp as root. The admin API
// must not set it verbatim — that turned any admin JWT into root on every site
// gateway (and a GET→PUT round trip would wipe the site's PrivateKey with the
// "(hidden)" placeholder). No UI path sends it.
function assertNoConfigText(data) {
	if (data && typeof data.config_text !== "undefined") {
		throw new error.ValidationError("config_text is generated by the hub and cannot be set via the API");
	}
}

/**
 * Refuse deleting an agent whose gateway may still run a restricted FG_IN filter.
 * Pure: `applied` is internalAgentIngress.appliedFor(agent).
 */
function assertIngressTornDown(agent, applied) {
	if ((agent.ingress_mode || "open") === "restricted") {
		throw new error.ValidationError(
			"Agent filtert noch („nur Freigaben“): erst auf „offen“ umstellen und warten, bis der Agent den Filter als gesetzt meldet",
		);
	}
	const appliedHash = applied?.applied_hash ?? null;
	if (appliedHash && appliedHash !== "NONE" && applied?.state !== "applied") {
		throw new error.ValidationError(
			"Der Agent hat den Wechsel auf „offen“ noch nicht übernommen: warten, bis er den Filter als gesetzt meldet",
		);
	}
}

/**
 * A forced delete skips assertIngressTornDown, so it is only allowed for an
 * agent that has not reported for this long (its site is gone / offline for
 * good — it could never confirm the switch to "open").
 */
const FORCE_DELETE_OFFLINE_S = 60 * 60;

/**
 * Pure: refuse a forced delete while the agent still reports in.
 *
 * @param {{ last_seen?: number|null }} agent
 * @param {number} [nowS]
 */
function assertForceDeleteAllowed(agent, nowS = Math.floor(Date.now() / 1000)) {
	const lastSeen = Number(agent?.last_seen) || 0;
	if (lastSeen && nowS - lastSeen < FORCE_DELETE_OFFLINE_S) {
		throw new error.ValidationError(
			`Erzwungenes Löschen nur für Agents, die sich seit mindestens ${FORCE_DELETE_OFFLINE_S / 60} Minuten nicht gemeldet haben: diesen Agent zuerst auf „offen“ umstellen`,
		);
	}
}

