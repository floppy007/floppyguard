/**
 * Generate a random hex token of `byteLength` bytes (returns 2*byteLength hex chars).
 *
 * @param {number} byteLength
 * @returns {string}
 */
const randomToken = (byteLength = 32) => randomBytes(byteLength).toString("hex");

/**
 * Tokens are generated by randomToken() (hex). Anything else - in particular a
 * JSON number/boolean from a request body - must never reach a WHERE clause:
 * MySQL compares a VARCHAR with a number numerically ('5b81...' = 5), which
 * would let a small integer match a pending agent's reg_token.
 *
 * @param {unknown} token
 * @returns {boolean}
 */
const isWellFormedToken = (token) => typeof token === "string" && /^[0-9a-fA-F]{32,128}$/.test(token);

/**
 * Compute SHA-256 hex digest of a string. Returns null if input is falsy.
 *
 * @param {string|null|undefined} text
 * @returns {string|null}
 */
const hashConfig = (text) => {
	if (!text) return null;
	return createHash("sha256").update(text).digest("hex");
};

